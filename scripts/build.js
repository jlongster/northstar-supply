"use strict";

// Bundles src/ into dist/app.js: one CommonJS file, `module.exports = App`, with `require("react")`
// left external. This is the file that the specializers (scripts/build-prepack.js,
// scripts/build-hybrid.js) and the servers consume.
//
// - JSX goes through Babel's classic runtime with `useBuiltIns` (the same transform the original
//   single-file app used), so `<button {...props}>` and spreads compile to plain objects /
//   Object.assign instead of object-spread syntax or esbuild helpers.
// - "react" resolves to a tiny virtual ES module whose default export is a free variable `React`,
//   bound by the banner to `require("react")`. Every component then refers to one plain variable
//   (`react_default.createElement(...)`) rather than going through esbuild's __toESM interop,
//   which keeps the bundle easy for the specializers to analyze.
// - The bundle is emitted as an ES module and its final `export { App as default }` is rewritten
//   to `module.exports = App` (no __toCommonJS / getter-based export objects).
const fs = require("fs");
const path = require("path");
const esbuild = require("esbuild");
const babel = require("@babel/core");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "dist", "app.js");

const reactExternal = {
  name: "react-external",
  setup(build) {
    build.onResolve({ filter: /^react$/ }, () => ({ path: "react", namespace: "react-external" }));
    build.onLoad({ filter: /.*/, namespace: "react-external" }, () => ({
      contents: "export default React;",
      loader: "js",
    }));
  },
};

const babelJsx = {
  name: "babel-jsx",
  setup(build) {
    build.onLoad({ filter: /\.jsx$/ }, async (args) => {
      const result = await babel.transformAsync(await fs.promises.readFile(args.path, "utf8"), {
        filename: args.path,
        configFile: false,
        babelrc: false,
        plugins: [["@babel/plugin-transform-react-jsx", { runtime: "classic", useBuiltIns: true }]],
      });
      return { contents: result.code, loader: "js" };
    });
  },
};

async function main() {
  const result = await esbuild.build({
    entryPoints: [path.join(ROOT, "src", "App.jsx")],
    bundle: true,
    write: false,
    format: "esm",
    platform: "neutral",
    target: "es5",
    charset: "utf8",
    legalComments: "none",
    plugins: [reactExternal, babelJsx],
  });
  const code = result.outputFiles[0].text;
  const exportRe = /\nexport \{\n  (\w+) as default\n\};\n$/;
  const m = exportRe.exec(code);
  if (!m) throw new Error("build: unexpected bundle tail (expected `export { App as default };`)");
  const out =
    "// GENERATED by `npm run build` (scripts/build.js) from src/. Do not edit.\n" +
    '"use strict";\n' +
    'var React = require("react");\n' +
    code.replace(exportRe, "\nmodule.exports = " + m[1] + ";\n");
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${out.length} bytes)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
