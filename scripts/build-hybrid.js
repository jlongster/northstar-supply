"use strict";

// Specializes dist/app.js with React-Hybrid (prepack-revived, hybrid/react/) and writes
// dist/render-hybrid.js: a standalone CommonJS module exporting render(data) -> html.
//
//   HYBRID_DIR=/path/to/prepack-revived-checkout node scripts/build-hybrid.js
//
// HYBRID_DIR must contain hybrid/react/ (and its node_modules with acorn). The default is the
// worktree used during development. The output never loads anything from HYBRID_DIR.
//
// React-Hybrid traces the real app under React on training requests, learns guarded templates and
// generates them as JS that runs in the app module's own scope (templates call the app's helpers
// such as formatMoney and cx). Its runtime source is therefore dist/app.js followed by
// `__hyOut.t = <templates>`. This script wraps that source in a CommonJS module function (instead
// of vm.compileFunction, so no eval at runtime) and adds the same render/fallback loop as
// hybrid/react/index.js makeRenderer: run the template; if a guard fails (or the app throws),
// render the request with ReactDOMServer.renderToString and the same App instance. React is
// therefore a runtime dependency (for createContext at load time and for fallbacks).
process.env.NODE_ENV = process.env.NODE_ENV || "production";
const fs = require("fs");
const path = require("path");
const React = require("react");
const ReactDOMServer = require("react-dom/server");
const { getTrainingCorpus } = require("../src/data.js");

const ROOT = path.join(__dirname, "..");
const HYBRID_DIR = process.env.HYBRID_DIR || "/tmp/opencode/pp-wt/react-hybrid";
const OUT = path.join(ROOT, "dist", "render-hybrid.js");
// React-Hybrid's defaults (hybrid/react/index.js): 60 small + 10 large training requests.
const TRAIN_SMALL = 60;
const TRAIN_LARGE = 10;

const hybrid = require(path.join(HYBRID_DIR, "hybrid", "react", "index.js"));
const appPath = path.join(ROOT, "dist", "app.js");
const appSource = fs.readFileSync(appPath, "utf8");
const result = hybrid.build(appSource, {
  React,
  ReactDOMServer,
  require,
  appPath,
  rootProp: "data",
  trainingInputs: getTrainingCorpus(TRAIN_SMALL, "small").concat(getTrainingCorpus(TRAIN_LARGE, "large")),
});
const stats = result.stats;
if (stats.disabled) throw new Error("build-hybrid: specialization disabled: " + stats.disabled);
console.log(
  `hybrid: built in ${Math.round(stats.buildMs)} ms: ${stats.templates} templates, ${stats.templateBytes} bytes of templates, ` +
    `${stats.framesLearned}/${stats.frames} frames learned, self-check mismatches ${stats.selfCheckMismatches}`
);
if (/\bnew Function\b|\beval\(/.test(result.templateCode)) throw new Error("build-hybrid: generated code uses eval");

const out = `// GENERATED by scripts/build-hybrid.js from dist/app.js with React-Hybrid
// (hybrid/react/ in github.com/jlongster/prepack-revived). Do not edit.
//
// render(data) returns exactly ReactDOMServer.renderToString(<App data={data} />). The templates
// (\`__hyOut.t\` at the end of the module function) were learned from ${TRAIN_SMALL + TRAIN_LARGE} traced training requests;
// every assumption they make is a runtime guard, and a failed guard renders the request with React.
"use strict";

var __hyOut = {};
var __hyModule = { exports: {} };
(function (exports, require, module, __hyOut) {
${result.code}
})(__hyModule.exports, require, __hyModule, __hyOut);

var App = __hyModule.exports;
var tpl = __hyOut.t;
var sites = ${JSON.stringify(result.sites)};
tpl.setDefaults(tpl.contexts.map(function (c) { return c._currentValue; }));

var React = require("react");
var ReactDOMServer = null;

function render(data) {
  try {
    return tpl.render(data);
  } catch (e) {
    var reason;
    if (tpl.isFallback(e)) {
      var site = tpl.lastFallbackSite();
      reason = site >= 0 ? sites[site] : "fallback";
    } else {
      reason = "error: " + (e && e.message);
    }
    render.stats.fallbacks++;
    render.stats.fallbackReasons[reason] = (render.stats.fallbackReasons[reason] || 0) + 1;
    if (ReactDOMServer === null) ReactDOMServer = require("react-dom/server");
    return ReactDOMServer.renderToString(React.createElement(App, { data: data }));
  }
}
render.stats = { fallbacks: 0, fallbackReasons: {} };

module.exports = { render: render };
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)} (${out.length} bytes)`);
