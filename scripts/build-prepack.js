"use strict";

// Specializes dist/app.js with the revived Prepack (prepack-revived, react-ssr/compiler.js) and
// writes dist/render-prepack.js: a standalone CommonJS module exporting render(data) -> html.
//
//   PREPACK_DIR=/path/to/prepack-revived-checkout node scripts/build-prepack.js
//
// PREPACK_DIR must be a built checkout (`yarn build-prepack`) that has react-ssr/. The default is
// the worktree used during development. The output never loads anything from PREPACK_DIR.
//
// What the compiler gives back is a script that, run with some object as `this`, defines
// this.__ssrRender (the specialized renderer; it never touches React) and this.__ssrConforms (a
// validator for the data schema the renderer was specialized for, inferred here from the training
// corpus). react-ssr loads it with `new Function(code).call(sandbox)`; this script inlines the code
// in a function instead (no eval at runtime), and adds the guard + fallback that the react-bench
// plug-in uses: data outside the schema is rendered with ReactDOMServer.renderToString and
// dist/app.js, loaded lazily on the first fallback.
const fs = require("fs");
const path = require("path");
const { getTrainingCorpus } = require("../src/data.js");

const ROOT = path.join(__dirname, "..");
const PREPACK_DIR = process.env.PREPACK_DIR || "/tmp/opencode/pp-wt/react-prepack";
const OUT = path.join(ROOT, "dist", "render-prepack.js");
// Same training set as the prepack react-bench plug-in (react-bench/impl/prepack.js).
const TRAINING_SMALL = 400;
const TRAINING_LARGE = 40;

const compiler = require(path.join(PREPACK_DIR, "react-ssr", "compiler.js"));
const appSource = fs.readFileSync(path.join(ROOT, "dist", "app.js"), "utf8");
const schema = compiler.inferSchema(getTrainingCorpus(TRAINING_SMALL, "small").concat(getTrainingCorpus(TRAINING_LARGE, "large")));
const started = Date.now();
const result = compiler.compile(appSource, { schema, rootProp: "data" });
console.log(`prepack: compiled in ${Date.now() - started} ms, ${result.code.length} bytes of specialized code`);
if (/\bnew Function\b|\beval\(/.test(result.code)) throw new Error("build-prepack: generated code uses eval");

const out = `// GENERATED by scripts/build-prepack.js from dist/app.js with the revived Prepack
// (react-ssr/compiler.js in github.com/jlongster/prepack-revived). Do not edit.
//
// render(data) returns exactly ReactDOMServer.renderToString(<App data={data} />). Data that
// matches the schema inferred at build time (${TRAINING_SMALL + TRAINING_LARGE} training requests) is rendered by the specialized
// code below, which does not use React; anything else falls back to React and dist/app.js.
"use strict";

var __ssr = Object.create(globalThis);
(function () {
${result.code}
}).call(__ssr);

var specialized = __ssr.__ssrRender;
var conforms = __ssr.__ssrConforms;
var fallbackRender = null;

function fallback(data) {
  if (fallbackRender === null) {
    var React = require("react");
    var ReactDOMServer = require("react-dom/server");
    var App = require("./app.js");
    fallbackRender = function (d) {
      return ReactDOMServer.renderToString(React.createElement(App, { data: d }));
    };
  }
  return fallbackRender(data);
}

function render(data) {
  if (conforms(data)) return specialized(data);
  render.stats.fallbacks++;
  return fallback(data);
}
render.stats = { fallbacks: 0 };

module.exports = { render: render };
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)} (${out.length} bytes)`);
